# 10. Save
# =============================================================================

def save_results(
    score_df: pd.DataFrame,
    rank_df: pd.DataFrame,
    friedman_df: pd.DataFrame,
    posthoc_df: pd.DataFrame,
    manuscript_df: pd.DataFrame,
    audit_df: pd.DataFrame,
    output_dir: Path,
):
    output_dir.mkdir(parents=True, exist_ok=True)

    # CSV
    score_df.to_csv(
        output_dir / "CrossNetwork_AggregateScores.csv",
        index=False,
        encoding="utf-8-sig",
        float_format="%.8f",
    )

    rank_df.to_csv(
        output_dir / "CrossNetwork_NetworkRanks.csv",
        index=False,
        encoding="utf-8-sig",
        float_format="%.8f",
    )

    friedman_df.to_csv(
        output_dir / "CrossNetwork_Friedman.csv",
        index=False,
        encoding="utf-8-sig",
        float_format="%.12g",
    )

    posthoc_df.to_csv(
        output_dir / "CrossNetwork_PostHoc_MSH_vs_Baselines.csv",
        index=False,
        encoding="utf-8-sig",
        float_format="%.12g",
    )

    manuscript_df.to_csv(
        output_dir / "Table_CrossNetwork_Manuscript.csv",
        index=False,
        encoding="utf-8-sig",
        float_format="%.8f",
    )

    audit_df.to_csv(
        output_dir / "CrossNetwork_Long_Audit.csv",
        index=False,
        encoding="utf-8-sig",
        float_format="%.8f",
    )

    # Excel workbook
    xlsx_path = output_dir / "CrossNetwork_Complete_Analysis.xlsx"

    with pd.ExcelWriter(
        xlsx_path,
        engine="openpyxl",
    ) as writer:
        manuscript_df.to_excel(
            writer,
            sheet_name="ManuscriptTable",
            index=False,
        )

        friedman_df.to_excel(
            writer,
            sheet_name="Friedman",
            index=False,
        )

        posthoc_df.to_excel(
            writer,
            sheet_name="PostHoc",
            index=False,
        )

        score_df.to_excel(
            writer,
            sheet_name="AggregateScores",
            index=False,
        )

        rank_df.to_excel(
            writer,
            sheet_name="NetworkRanks",
            index=False,
        )

        audit_df.to_excel(
            writer,
            sheet_name="AuditLong",
            index=False,
        )

    print("\n[Saved]")
    print(f"  {xlsx_path}")
    print(f"  {output_dir / 'Table_CrossNetwork_Manuscript.csv'}")
    print(f"  {output_dir / 'CrossNetwork_Friedman.csv'}")
    print(f"  {output_dir / 'CrossNetwork_PostHoc_MSH_vs_Baselines.csv'}")


