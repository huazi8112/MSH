# =============================================================================
# 1. Benjamini-Hochberg correction
# =============================================================================

def benjamini_hochberg(p_values):
    """
    Benjamini-Hochberg FDR correction.
    Returns adjusted p-values in the original order.
    """
    p = np.asarray(p_values, dtype=float)
    n = len(p)

    if n == 0:
        return np.asarray([], dtype=float)

    order = np.argsort(p)
    ranked = p[order]

    adjusted_ranked = ranked * n / np.arange(1, n + 1)
    adjusted_ranked = np.minimum.accumulate(adjusted_ranked[::-1])[::-1]
    adjusted_ranked = np.clip(adjusted_ranked, 0.0, 1.0)

    adjusted = np.empty(n, dtype=float)
    adjusted[order] = adjusted_ranked

    return adjusted


# =============================================================================
# 2. Matched-pairs rank-biserial correlation
# =============================================================================

def matched_pairs_rank_biserial(x, y):
    """
    Matched-pairs rank-biserial correlation for paired observations.

    Differences are defined as:
        d = x - y

    Here x = MSH aggregate score and y = baseline aggregate score.

    Positive r_rb -> MSH tends to be larger.
    Negative r_rb -> baseline tends to be larger.

    Zero differences are removed. Absolute nonzero differences are ranked
    using average ranks for ties.
    """
    x = np.asarray(x, dtype=float)
    y = np.asarray(y, dtype=float)

    if x.shape != y.shape:
        raise ValueError("Paired arrays x and y must have the same shape.")

    d = x - y

    # Remove exact zero differences, consistent with Wilcoxon zero_method='wilcox'.
    d = d[d != 0]

    if len(d) == 0:
        return 0.0, 0.0, 0.0, 0

    ranks = rankdata(np.abs(d), method="average")

    w_plus = float(np.sum(ranks[d > 0]))
    w_minus = float(np.sum(ranks[d < 0]))

    denom = w_plus + w_minus
    r_rb = (w_plus - w_minus) / denom if denom > 0 else 0.0

    return float(r_rb), w_plus, w_minus, len(d)


# =============================================================================
# 3. Input validation
# =============================================================================

def find_result_file(input_dir: Path, network: str) -> Path:
    candidates = [
        input_dir / f"SIR_AllData_{network}.xlsx",
        input_dir / f"SIR_AllData_{NETWORK_DISPLAY[network]}.xlsx",
    ]

    for p in candidates:
        if p.exists():
            return p

    tried = "\n".join(str(p) for p in candidates)
    raise FileNotFoundError(
        f"Cannot find SIR result file for network '{network}'.\nTried:\n{tried}"
    )


def check_seed_ratios(df: pd.DataFrame, file_path: Path):
    if "Seed_Ratio_%" not in df.columns:
        raise ValueError(
            f"{file_path} does not contain column 'Seed_Ratio_%'."
        )

    ratios = pd.to_numeric(
        df["Seed_Ratio_%"],
        errors="coerce",
    ).to_numpy(dtype=float)

    if len(ratios) != 10 or np.any(~np.isfinite(ratios)):
        raise ValueError(
            f"{file_path}: expected exactly 10 valid seed-ratio rows."
        )

    if not np.allclose(
        np.sort(ratios),
        EXPECTED_RATIOS,
        atol=1e-6,
        rtol=0.0,
    ):
        raise ValueError(
            f"{file_path}: seed ratios must be 1%,2%,...,10%.\n"
            f"Observed: {ratios}"
        )


# =============================================================================
# 4. Build network-level aggregate performance table
# =============================================================================

def build_aggregate_scores(input_dir: Path) -> pd.DataFrame:
    """
    Returns a 9 x 12 network-level aggregate performance table.

    Each cell is:
        mean F(tc) across p = 1%,...,10%
    """
    records = []

    for network in NETWORKS:
        file_path = find_result_file(input_dir, network)
        df = pd.read_excel(file_path)

        check_seed_ratios(df, file_path)

        # Sort by seed ratio before aggregation for audit consistency.
        df = df.sort_values("Seed_Ratio_%").reset_index(drop=True)

        row = {
            "Network": NETWORK_DISPLAY[network],
        }

        for method in METHODS_INTERNAL:
            col = f"{method}_Mean(%)"

            if col not in df.columns:
                raise ValueError(
                    f"{file_path} is missing required column '{col}'."
                )

            values = pd.to_numeric(
                df[col],
                errors="coerce",
            ).to_numpy(dtype=float)

            if len(values) != 10 or np.any(~np.isfinite(values)):
                raise ValueError(
                    f"{file_path}: invalid values in column '{col}'."
                )

            row[METHOD_DISPLAY[method]] = float(np.mean(values))

        records.append(row)

        print(
            f"[Loaded] {NETWORK_DISPLAY[network]:<9s} "
            f"<- {file_path.name}"
        )

    return pd.DataFrame(records)


# =============================================================================
# 5. Within-network ranks
# =============================================================================

def build_network_ranks(score_df: pd.DataFrame) -> pd.DataFrame:
    """
    Rank the 12 methods separately in each network.
    Rank 1 = best/highest aggregate F(tc).
    Ties receive average ranks.
    """
    methods = [METHOD_DISPLAY[m] for m in METHODS_INTERNAL]

    records = []

    for _, row in score_df.iterrows():
        scores = np.array(
            [float(row[m]) for m in methods],
            dtype=float,
        )

        # scipy rankdata assigns rank 1 to smallest, hence negate.
        ranks = rankdata(
            -scores,
            method="average",
        )

        rec = {
            "Network": row["Network"],
        }

        for m, r in zip(methods, ranks):
            rec[m] = float(r)

        records.append(rec)

    return pd.DataFrame(records)


# =============================================================================
# 6. Friedman omnibus test
# =============================================================================

def run_friedman(score_df: pd.DataFrame) -> pd.DataFrame:
    methods = [METHOD_DISPLAY[m] for m in METHODS_INTERNAL]

    method_arrays = [
        score_df[m].to_numpy(dtype=float)
        for m in methods
    ]

    chi2, p_value = friedmanchisquare(*method_arrays)

    n_networks = len(score_df)
    n_methods = len(methods)

    kendalls_w = (
        float(chi2)
        / (n_networks * (n_methods - 1))
    )

    return pd.DataFrame([{
        "Test": "Friedman",
        "Aggregation": "Mean F(tc) over seed ratios 1%-10% within each network",
        "Statistical_unit": "Network",
        "N_networks": n_networks,
        "N_methods": n_methods,
        "Chi_square_F": float(chi2),
        "df": n_methods - 1,
        "P_value": float(p_value),
        "Kendalls_W": float(kendalls_w),
    }])


# =============================================================================
# 7. MSH-vs-baseline post-hoc tests
# =============================================================================

def run_posthoc_vs_msh(score_df: pd.DataFrame) -> pd.DataFrame:
    """
    Pair MSH with each baseline across the 9 network-level aggregate scores.

    Multiple-comparison family:
        11 comparisons (MSH vs each baseline)

    Test:
        two-sided paired Wilcoxon signed-rank test

    Effect size:
        matched-pairs rank-biserial correlation
    """
    target = score_df[TARGET_DISPLAY].to_numpy(dtype=float)

    records = []

    for baseline_internal in METHODS_INTERNAL:
        if baseline_internal == TARGET_INTERNAL:
            continue

        baseline = METHOD_DISPLAY[baseline_internal]
        comp = score_df[baseline].to_numpy(dtype=float)

        diff = target - comp
        n_positive = int(np.sum(diff > 0))
        n_negative = int(np.sum(diff < 0))
        n_zero = int(np.sum(diff == 0))

        try:
            # method='auto' uses exact calculation when available.
            stat, p_raw = wilcoxon(
                target,
                comp,
                alternative="two-sided",
                zero_method="wilcox",
                correction=False,
                method="auto",
            )
            p_raw = float(p_raw)
            stat = float(stat)
        except ValueError:
            stat = 0.0
            p_raw = 1.0

        r_rb, w_plus, w_minus, n_nonzero = matched_pairs_rank_biserial(
            target,
            comp,
        )

        records.append({
            "Comparison": f"{TARGET_DISPLAY} vs {baseline}",
            "Baseline": baseline,
            "N_networks": len(score_df),
            "N_positive_MSH": n_positive,
            "N_negative_MSH": n_negative,
            "N_zero": n_zero,
            "N_nonzero": n_nonzero,
            "Wilcoxon_statistic": stat,
            "P_raw": p_raw,
            "W_plus": w_plus,
            "W_minus": w_minus,
            "r_rb": r_rb,
        })

    posthoc = pd.DataFrame(records)

    posthoc["P_BH"] = benjamini_hochberg(
        posthoc["P_raw"].to_numpy(dtype=float)
    )

    posthoc["Significant_BH_0.05"] = (
        posthoc["P_BH"] < 0.05
    )

    return posthoc


# =============================================================================
# 8. Final manuscript table
# =============================================================================

def build_manuscript_table(
    score_df: pd.DataFrame,
    rank_df: pd.DataFrame,
    posthoc_df: pd.DataFrame,
) -> pd.DataFrame:
    methods = [METHOD_DISPLAY[m] for m in METHODS_INTERNAL]

    posthoc_by_baseline = (
        posthoc_df
        .set_index("Baseline")
        .to_dict(orient="index")
    )

    records = []

    for method in methods:
        ranks = rank_df[method].to_numpy(dtype=float)

        avg_rank = float(np.mean(ranks))

        # Strict rank-1 count. If a network has a tie for first and both
        # receive rank 1.5, neither is counted as strict rank 1.
        rank1_count = int(np.sum(np.isclose(ranks, 1.0)))

        if method == TARGET_DISPLAY:
            p_bh = np.nan
            r_rb = np.nan
        else:
            p_bh = float(posthoc_by_baseline[method]["P_BH"])
            r_rb = float(posthoc_by_baseline[method]["r_rb"])

        records.append({
            "Method": method,
            "Average_Rank": avg_rank,
            "Rank1_Count": rank1_count,
            "P_BH_vs_MSH": p_bh,
            "r_rb_vs_MSH": r_rb,
        })

    table = pd.DataFrame(records)

    # Lower average rank is better.
    table = (
        table
        .sort_values(
            ["Average_Rank", "Method"],
            ascending=[True, True],
        )
        .reset_index(drop=True)
    )

    return table


# =============================================================================
# 9. Audit table: network-level aggregate score + rank
# =============================================================================

def build_long_audit_table(
    score_df: pd.DataFrame,
    rank_df: pd.DataFrame,
) -> pd.DataFrame:
    methods = [METHOD_DISPLAY[m] for m in METHODS_INTERNAL]

    rows = []

    for i in range(len(score_df)):
        network = score_df.loc[i, "Network"]

        for method in methods:
            rows.append({
                "Network": network,
                "Method": method,
                "Aggregate_F_mean_1to10(%)": float(score_df.loc[i, method]),
                "Within_network_rank": float(rank_df.loc[i, method]),
            })

    return pd.DataFrame(rows)


