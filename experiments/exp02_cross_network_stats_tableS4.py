"""
Section 4.1.1 — Cross-network aggregate comparison
Average rank + Friedman test + post-hoc paired Wilcoxon + BH correction
+ matched-pairs rank-biserial effect size

IMPORTANT
---------
This is a POST-PROCESSING script for the existing Section 4.1.1 SIR experiment.
It does NOT rerun SIR simulations.

Input files are the per-network Excel files already generated by the original
4.1.1 code, for example:

results/exp_sir_influence/
    SIR_AllData_lesmis.xlsx
    SIR_AllData_adjnoun.xlsx
    SIR_AllData_jazz.xlsx
    SIR_AllData_usair.xlsx
    SIR_AllData_infect.xlsx
    SIR_AllData_email.xlsx
    SIR_AllData_polblogs.xlsx
    SIR_AllData_hamster.xlsx
    SIR_AllData_power.xlsx

Statistical design
------------------
For each network d and method m, first aggregate the ten seed-ratio settings:

    A_{m,d} = mean_{p=1%,...,10%} F_{m,d}(t_c; p)

Each network therefore contributes ONE aggregate observation per method.

Then:
1) Rank all 12 methods within each network.
   Higher A_{m,d} -> better/smaller rank.
2) Compute the average rank over the 9 networks.
3) Friedman omnibus test:
       blocks     = 9 networks
       treatments = 12 methods
4) Omnibus standardized effect size:
       Kendall's W = chi_square_F / [n_networks * (n_methods - 1)]
5) If desired, post-hoc comparisons are performed between MSH and each of
   the 11 baselines using paired Wilcoxon signed-rank tests across the SAME
   9 network-level aggregate observations.
6) The 11 post-hoc p-values are corrected together using Benjamini-Hochberg.
7) Matched-pairs rank-biserial correlation is reported as:

       r_rb = (W_plus - W_minus) / (W_plus + W_minus)

   Positive r_rb favors MSH; negative r_rb favors the baseline.

Main manuscript table
---------------------
The script creates a compact table with:
    Method
    Average rank
    Rank-1 count
    p_BH vs MSH
    r_rb vs MSH

For the MSH row, post-hoc columns are left blank.

Notes
-----
- Internal code name HOSH is displayed as MSH in manuscript-facing output.
- No node-ID tie-breaking is involved in this cross-network analysis.
- Ties among method aggregate scores within a network receive average ranks.
- The statistical unit for the Friedman and post-hoc tests is NETWORK (n=9),
  not the 90 network × seed-ratio cells.
"""

