# 11. Console report
# =============================================================================

def print_console_report(
    manuscript_df: pd.DataFrame,
    friedman_df: pd.DataFrame,
    posthoc_df: pd.DataFrame,
):
    print("\n" + "=" * 88)
    print("MANUSCRIPT TABLE")
    print("=" * 88)

    print(
        manuscript_df.to_string(
            index=False,
            formatters={
                "Average_Rank": lambda x: f"{x:.3f}",
                "P_BH_vs_MSH": (
                    lambda x: "—"
                    if pd.isna(x)
                    else f"{x:.6g}"
                ),
                "r_rb_vs_MSH": (
                    lambda x: "—"
                    if pd.isna(x)
                    else f"{x:.3f}"
                ),
            },
        )
    )

    fr = friedman_df.iloc[0]

    print("\n" + "=" * 88)
    print("FRIEDMAN OMNIBUS TEST")
    print("=" * 88)

    print(
        f"Statistical unit: network\n"
        f"n_networks = {int(fr['N_networks'])}\n"
        f"k_methods = {int(fr['N_methods'])}\n"
        f"chi-square_F = {fr['Chi_square_F']:.6f}\n"
        f"df = {int(fr['df'])}\n"
        f"p = {fr['P_value']:.8g}\n"
        f"Kendall's W = {fr['Kendalls_W']:.6f}"
    )

    print("\n" + "=" * 88)
    print("POST-HOC: MSH VS 11 BASELINES")
    print("=" * 88)

    cols = [
        "Baseline",
        "N_positive_MSH",
        "N_negative_MSH",
        "P_raw",
        "P_BH",
        "r_rb",
    ]

    print(
        posthoc_df[cols].to_string(
            index=False,
            formatters={
                "P_raw": lambda x: f"{x:.6g}",
                "P_BH": lambda x: f"{x:.6g}",
                "r_rb": lambda x: f"{x:.3f}",
            },
        )
    )


# =============================================================================
# 12. Main
# =============================================================================

def main(input_dir: Path, output_dir: Path):
    print("=" * 88)
    print("Section 4.1.1 cross-network aggregate analysis")
    print("=" * 88)
    print(f"Input directory : {input_dir}")
    print(f"Output directory: {output_dir}")
    print("SIR rerun       : NO")
    print("Aggregation     : equal-weight mean over p = 1%-10%")
    print("Statistical unit: network (n=9)")
    print("Post-hoc family : MSH vs 11 baselines, BH corrected")

    score_df = build_aggregate_scores(input_dir)
    rank_df = build_network_ranks(score_df)
    friedman_df = run_friedman(score_df)
    posthoc_df = run_posthoc_vs_msh(score_df)

    manuscript_df = build_manuscript_table(
        score_df,
        rank_df,
        posthoc_df,
    )

    audit_df = build_long_audit_table(
        score_df,
        rank_df,
    )

    save_results(
        score_df,
        rank_df,
        friedman_df,
        posthoc_df,
        manuscript_df,
        audit_df,
        output_dir,
    )

    print_console_report(
        manuscript_df,
        friedman_df,
        posthoc_df,
    )


if __name__ == "__main__":
    parser = argparse.ArgumentParser(
        description=(
            "Cross-network average rank, Friedman test, "
            "MSH-vs-baseline Wilcoxon post-hoc tests, BH correction, "
            "and rank-biserial effect sizes for Section 4.1.1."
        )
    )

    parser.add_argument(
        "--input-dir",
        type=Path,
        default=DEFAULT_INPUT_DIR,
        help=(
            "Directory containing SIR_AllData_<network>.xlsx files."
        ),
    )

    parser.add_argument(
        "--output-dir",
        type=Path,
        default=DEFAULT_OUTPUT_DIR,
        help="Directory for aggregate statistical outputs.",
    )

    args = parser.parse_args()

    main(
        input_dir=args.input_dir,
        output_dir=args.output_dir,
    )
